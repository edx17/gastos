/**
 * Generates the SQL category taxonomy from the TypeScript source of truth
 * (`src/constants/categories.ts`) so both stacks can never drift apart.
 *
 *   node scripts/generate-category-seed.mjs > supabase/migrations/<n>_categories.sql
 */
import { readFile } from 'node:fs/promises';
import { transform } from 'esbuild';

const source = await readFile(new URL('../src/constants/categories.ts', import.meta.url), 'utf8');
const { code } = await transform(source, { loader: 'ts', format: 'esm' });
const module = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);

const payload = module.DEFAULT_CATEGORIES.map((category) => ({
  slug: category.slug,
  name: category.name,
  kind: category.kind,
  icon: category.icon,
  color: category.color,
  subcategories: category.subcategories.map((sub) => ({
    slug: sub.slug,
    name: sub.name,
    keywords: sub.keywords,
  })),
}));

const json = JSON.stringify(payload).replace(/'/g, "''");

process.stdout.write(`-- Generated by scripts/generate-category-seed.mjs — do not edit by hand.
-- Source of truth: src/constants/categories.ts

create or replace function public.default_category_taxonomy()
returns jsonb
language sql
immutable
as $function$
  select '${json}'::jsonb;
$function$;

comment on function public.default_category_taxonomy() is
  'Categorías y subcategorías por defecto (generadas desde src/constants/categories.ts).';
`);
